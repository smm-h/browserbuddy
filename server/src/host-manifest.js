import crypto from 'node:crypto';

/**
 * The native-messaging host name. It is the only handle the extension has on
 * the host process, and it must match the manifest filename exactly.
 */
export const HOST_NAME = 'com.browserbuddy.host';

/** The gecko id declared in extension/manifest.json. */
export const FIREFOX_EXTENSION_ID = 'browserbuddy@localhost';

/**
 * Chrome derives an unpacked extension's id from the "key" in its manifest
 * when one is present (and from the extension's absolute path when it is not,
 * which is why the key exists: allowed_origins must name a stable id).
 *
 * The id is the first 128 bits of SHA-256 over the DER SubjectPublicKeyInfo,
 * rendered in Chrome's a-p alphabet.
 */
export function chromeExtensionIdFromKey(base64Key) {
  const der = Buffer.from(base64Key, 'base64');
  const digest = crypto.createHash('sha256').update(der).digest('hex').slice(0, 32);
  let id = '';
  for (const ch of digest) id += String.fromCharCode(97 + parseInt(ch, 16));
  return id;
}

/**
 * Chrome/Chromium host manifest. Chrome looks for it at
 * <user-data-dir>/NativeMessagingHosts/<HOST_NAME>.json -- i.e. it follows
 * --user-data-dir, which is what lets a test profile install its own host
 * without touching ~/.config/chromium.
 */
export function chromeHostManifest({ hostPath, extensionId }) {
  return {
    name: HOST_NAME,
    description: 'BrowserBuddy native messaging host (serves MCP over loopback HTTP).',
    path: hostPath,
    type: 'stdio',
    allowed_origins: [`chrome-extension://${extensionId}/`]
  };
}

/**
 * Firefox host manifest. Firefox looks for it at
 * $HOME/.mozilla/native-messaging-hosts/<HOST_NAME>.json on Linux -- keyed on
 * HOME, not on the profile, so a test run must override HOME to stay out of
 * the user's real Firefox configuration.
 */
export function firefoxHostManifest({ hostPath, extensionId = FIREFOX_EXTENSION_ID }) {
  return {
    name: HOST_NAME,
    description: 'BrowserBuddy native messaging host (serves MCP over loopback HTTP).',
    path: hostPath,
    type: 'stdio',
    allowed_extensions: [extensionId]
  };
}

/**
 * The launcher the manifest's "path" points at. The browser spawns it with a
 * minimal environment, so nothing may be resolved through PATH: both the node
 * binary and the host script are absolute, and --data-dir is baked in because
 * the browser appends its own arguments after ours.
 */
export function launcherScript({ nodePath, hostScript, dataDir }) {
  return (
    '#!/bin/sh\n' +
    '# Generated by scripts/install-native-host.mjs -- do not edit.\n' +
    '# The browser execs this file and speaks native messaging over its stdio.\n' +
    `exec ${JSON.stringify(nodePath)} ${JSON.stringify(hostScript)} --data-dir ${JSON.stringify(dataDir)} "$@"\n`
  );
}
